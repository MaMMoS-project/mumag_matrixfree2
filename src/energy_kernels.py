"""energy_kernels.py.

Micromagnetic energy + gradient kernels on tetrahedral P1 FEM meshes.
Optimized for speed and consistency using the property:
E = 0.5 * sum(m * (g_total + g_zeeman))

Energy Scaling and Physical Units:
----------------------------------
This implementation uses a dimensionless scaling based on the reference
saturation magnetization Js_ref (Tesla) and the associated energy density:
    Kd_ref = Js_ref^2 / (2 * mu0)  [J/m^3]

Dimensionless variables:
    m = M / Js             (Unit vector)
    Js_red = Js / Js_ref   (Dimensionless)
    B_red = B_ext / Js_ref (Dimensionless)
    u = (mu0 / Js_ref) * u_calc (Dimensionless potential)

Energy Normalization (E_dimensionless = E_SI / (Kd_ref * Vmag)):
    1. Exchange:   E_ex  = (1/Vmag) * Integral( A_red * |grad m|^2 ) dV
    2. Anisotropy: E_an  = (1/Vmag) * Integral( K1_red * [1 - (m.k)^2] ) dV
    3. Zeeman:     E_z   = (1/Vmag) * Integral( -2 * Js_red * m . B_red ) dV
    4. Demag:      E_dem = (1/Vmag) * Integral( Js_red * m . grad(u) ) dV

    Note: The factor '2' in Zeeman arises because 1/Kd_ref = 2*mu0/Js_ref^2.
    Note: The factor '1/2' in physical Demag (0.5 * M . Hd) is cancelled
    by the '2' in the denominator of Kd_ref, resulting in a factor of 1.

Physical Field Conversions:
    - Scalar Potential [A]:      U_phys = (Js_ref / mu0) * u
    - Demag Field Hd [A/m]:      Hd = -grad(U_phys) = -(Js_ref / mu0) * grad(u)
    - Demag Field mu0*Hd [T]:    mu0*Hd = -Js_ref * grad(u)

Gradient Property:
    For quadratic terms (Ex, An, Demag), m^T * g = 2 * E.
    For linear terms (Zeeman), m^T * g = E.
    Thus, E_total = 0.5 * m^T * (g_quadratic + 2 * g_zeeman)
                   = 0.5 * m^T * (g_total + g_zeeman).

Author: generated by M365 Copilot
License: MIT
"""

