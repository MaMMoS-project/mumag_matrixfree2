"""energy_kernels.py.

Micromagnetic energy + gradient kernels on tetrahedral P1 FEM meshes.
Optimized for speed and consistency using the property:
E = 0.5 * sum(m * (g_total + g_zeeman))

Energy Scaling and Physical Units:
----------------------------------
This implementation uses a dimensionless scaling based on the reference
saturation magnetization Js_ref (Tesla) and the associated energy density:
    Kd_ref = Js_ref^2 / (2 * mu0)  [J/m^3]

Dimensionless variables:
    m = M / Js             (Unit vector)
    Js_red = Js / Js_ref   (Dimensionless)
    B_red = B_ext / Js_ref (Dimensionless)
    u = (mu0 / Js_ref) * u_calc (Dimensionless potential)

Energy Normalization (E_dimensionless = E_SI / (Kd_ref * Vmag)):
    1. Exchange:   E_ex  = (1/Vmag) * Integral( A_red * |grad m|^2 ) dV
    2. Anisotropy: E_an  = (1/Vmag) * Integral( K1_red * [1 - (m.k)^2] ) dV
    3. Zeeman:     E_z   = (1/Vmag) * Integral( -2 * Js_red * m . B_red ) dV
    4. Demag:      E_dem = (1/Vmag) * Integral( Js_red * m . grad(u) ) dV

    Note: The factor '2' in Zeeman arises because 1/Kd_ref = 2*mu0/Js_ref^2.
    Note: The factor '1/2' in physical Demag (0.5 * M . Hd) is cancelled
    by the '2' in the denominator of Kd_ref, resulting in a factor of 1.

Physical Field Conversions:
    - Scalar Potential [A]:      U_phys = (Js_ref / mu0) * u
    - Demag Field Hd [A/m]:      Hd = -grad(U_phys) = -(Js_ref / mu0) * grad(u)
    - Demag Field mu0*Hd [T]:    mu0*Hd = -Js_ref * grad(u)

Gradient Property:
    For quadratic terms (Ex, An, Demag), m^T * g = 2 * E.
    For linear terms (Zeeman), m^T * g = E.
    Thus, E_total = 0.5 * m^T * (g_quadratic + 2 * g_zeeman)
                   = 0.5 * m^T * (g_total + g_zeeman).

Author: generated by M365 Copilot
License: MIT
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Literal

import jax

jax.config.update("jax_enable_x64", True)
import jax.numpy as jnp  # noqa: E402

from fem_utils import TetGeom

MU0 = 4e-7 * jnp.pi
Array = jnp.ndarray

GradBackend = Literal["stored_grad_phi", "stored_JinvT", "on_the_fly"]
Assembly = Literal["scatter", "segment_sum"]


def make_energy_kernels(  # noqa: D417
    geom: TetGeom,
    A_lookup: Array,
    K1_lookup: Array,
    Js_lookup: Array,
    k_easy_lookup: Array,
    V_mag: float,
    M_nodal: Array,
    *,
    B_bias: Array | None = None,
    k1me: Array | None = None,
    k1me_p: Array | None = None,
    chunk_elems: int = 200_000,
    assembly: Assembly = "segment_sum",
    grad_backend: GradBackend = "stored_grad_phi",
    Kex_sparse: Any | None = None,
    Kan_sparse: Any | None = None,
    k_nodes: Array | None = None,
) -> tuple[
    Callable[[Array, Array, Array], tuple[Array, Array]],
    Callable[[Array, Array, Array], Array],
    Callable[[Array, Array, Array], Array],
    Callable[[Array], Array],
]:
    """Create JIT-compiled micromagnetic energy and gradient functions in matrix-free or matrix-assembled mode.

    Returns a quartet of functions (energy_and_grad, energy_only, grad_only, local_grad_only).
    All calculations use dimensionless scaling.

    Args:
        geom (TetGeom): Geometry container.
        A_lookup (Array): Dimensionless exchange constants for each material.
        K1_lookup (Array): Dimensionless anisotropy constants for each material.
        Js_lookup (Array): Dimensionless saturation polarization for each material.
        k_easy_lookup (Array): Easy axis vectors (unit length) for each material (G, 3).
        V_mag (float): Total magnetic volume in mesh units (e.g., nm^3).
        M_nodal (Array): Nodal magnetic moment scaling (N,).
        B_bias (Array | None, optional): Per-node bias field for mode initialization.
        k1me (Array | None, optional): Per-element magnetoelastic constant Kx.
        k1me_p (Array | None, optional): Per-element magnetoelastic constant Ky.
        chunk_elems (int, optional): Elements processed per loop iteration.
            Defaults to 200_000.
        assembly (Assembly, optional): Nodal assembly method
            ('scatter' or 'segment_sum'). Defaults to 'scatter'.
        grad_backend (GradBackend, optional): Strategy for shape function gradients.
            'stored_grad_phi', 'stored_JinvT', or 'on_the_fly'.
            Defaults to 'stored_grad_phi'.
        Kex_sparse (Any | None): Assembled exchange matrix in JAX BCOO format.
        Kan_sparse (Any | None): Assembled anisotropy matrix in JAX BCOO format.
        k_nodes (Array | None): Precomputed easy axis per node (N, 3).

    Returns:
        tuple[Callable, Callable, Callable, Callable]: (energy_and_grad, energy_only, grad_only, local_grad_only).
            Each function takes (m, U, B_ext) as input, except local_grad_only which takes only v.
    """
    inv_Vmag = 1.0 / V_mag


    def energy_and_grad(m: Array, U: Array, B_ext: Array, sparse_ops: dict = None) -> tuple[Array, Array]:
        N = m.shape[0]
        dtype = m.dtype
        B_ext = jnp.asarray(B_ext, dtype=dtype)

        # Using K_eff which combines Exchange and Anisotropy
        m_flat = m.reshape(-1)
        g_ex_an_flat = sparse_ops["K_eff_sparse"] @ m_flat
        g_ex_an = g_ex_an_flat.reshape(N, 3)

        # 3. Demag gradient: G @ U (shape (N, 3))
        g_dem_flat = sparse_ops["G_sparse"] @ U
        g_dem = g_dem_flat.reshape(-1, 3)

        # 4. Zeeman gradient
        B_eff = B_ext[None, :]
        B_bias_dyn = sparse_ops.get("B_bias")
        if B_bias_dyn is not None:
            B_eff = B_eff + B_bias_dyn
        M_nodal_dyn = sparse_ops["M_nodal"]
        g_z = -2.0 * M_nodal_dyn[:, None] * B_eff

        # Total gradient
        g_total = g_ex_an + g_dem + g_z

        # Energy calculation trick: E = 0.5 * sum(m * (g_total + g_z))
        E = 0.5 * jnp.sum(m * (g_total + g_z))
        return E * inv_Vmag, g_total * inv_Vmag

    def energy_only(m: Array, U: Array, B_ext: Array, sparse_ops: dict = None) -> Array:
        E, _ = energy_and_grad(m, U, B_ext, sparse_ops)
        return E

    def grad_only(m: Array, U: Array, B_ext: Array, sparse_ops: dict = None) -> Array:
        _, g = energy_and_grad(m, U, B_ext, sparse_ops)
        return g

    def local_grad_only(v: Array, sparse_ops: dict = None) -> Array:
        N = v.shape[0]
        v_flat = v.reshape(-1)
        g_flat = sparse_ops["K_eff_sparse"] @ v_flat
        g_ex_an = g_flat.reshape(N, 3)
        return g_ex_an * inv_Vmag

    return jax.jit(energy_and_grad), jax.jit(energy_only), jax.jit(grad_only), jax.jit(local_grad_only)


